/** Days from the fixture's "today" (2026-10-04), so tests don't depend on the real clock. */
export function fixtureDaysUntil(date: string) {
  return Math.round(
    (Date.parse(`${date}T00:00:00Z`) - Date.parse("2026-10-04T00:00:00Z")) / 86_400_000,
  );
}
